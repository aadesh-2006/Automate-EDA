import base64
from html import escape

from app.eda import profile_csv
from app.services.visualization import (
    create_correlation_heatmap,
    create_histogram,
)


def generate_html_report(csv_content: str) -> str:
    """Generate a standalone HTML report containing EDA statistics and charts."""
    profile = profile_csv(csv_content)

    charts = []
    numeric_columns = [
        column["name"]
        for column in profile["columns"]
        if column["dtype"] in {"int64", "int32", "float64", "float32"}
    ]

    for column in numeric_columns[:3]:
        try:
            image = create_histogram(csv_content, column)
            encoded = base64.b64encode(image).decode("ascii")
            charts.append(
                f'<section><h3>Distribution: {escape(column)}</h3>'
                f'<img alt="Histogram of {escape(column)}" '
                f'src="data:image/png;base64,{encoded}"></section>'
            )
        except ValueError:
            continue

    if len(numeric_columns) >= 2:
        try:
            image = create_correlation_heatmap(csv_content)
            encoded = base64.b64encode(image).decode("ascii")
            charts.append(
                '<section><h2>Correlation Heatmap</h2>'
                f'<img alt="Correlation heatmap" '
                f'src="data:image/png;base64,{encoded}"></section>'
            )
        except ValueError:
            pass

    column_rows = "".join(
        "<tr>"
        f"<td>{escape(column['name'])}</td>"
        f"<td>{escape(column['dtype'])}</td>"
        f"<td>{column['missing_values']}</td>"
        f"<td>{column['missing_percentage']:.2f}%</td>"
        f"<td>{column['unique_values']}</td>"
        "</tr>"
        for column in profile["columns"]
    )

    numeric_summary = escape(str(profile["numeric_summary"]))

    return f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>DataLens AI - EDA Report</title>
<style>
body {{ font-family: Arial, sans-serif; max-width: 1100px; margin: 40px auto;
       padding: 0 20px; color: #202938; line-height: 1.6; }}
h1, h2 {{ color: #174ea6; }}
.cards {{ display: flex; flex-wrap: wrap; gap: 16px; }}
.card {{ background: #eef4ff; padding: 16px; border-radius: 8px;
         min-width: 140px; }}
table {{ border-collapse: collapse; width: 100%; margin: 20px 0; }}
th, td {{ border: 1px solid #d8dee9; padding: 10px; text-align: left; }}
th {{ background: #eef4ff; }}
img {{ max-width: 100%; height: auto; }}
section {{ margin: 28px 0; }}
pre {{ white-space: pre-wrap; overflow-wrap: anywhere; }}
</style>
</head>
<body>
<h1>DataLens AI — Exploratory Data Analysis</h1>
<p>Automatically generated report from your CSV dataset.</p>
<div class="cards">
<div class="card"><strong>Rows</strong><br>{profile['rows']}</div>
<div class="card"><strong>Columns</strong><br>{profile['columns_count']}</div>
<div class="card"><strong>Missing values</strong><br>{profile['missing_values_total']}</div>
<div class="card"><strong>Duplicate rows</strong><br>{profile['duplicate_rows']}</div>
</div>
<h2>Column Overview</h2>
<table>
<thead><tr><th>Column</th><th>Data type</th><th>Missing</th>
<th>Missing %</th><th>Unique values</th></tr></thead>
<tbody>{column_rows}</tbody>
</table>
<h2>Numeric Summary</h2>
<pre>{numeric_summary}</pre>
<h2>Visualizations</h2>
{''.join(charts) if charts else '<p>No suitable numeric charts were available.</p>'}
<footer><p>Generated by DataLens AI.</p></footer>
</body>
</html>"""

def generate_pdf_report(csv_content: str) -> bytes:
    """Generate a downloadable PDF report containing EDA statistics and charts."""
    from io import BytesIO

    from reportlab.lib import colors
    from reportlab.lib.enums import TA_CENTER
    from reportlab.lib.pagesizes import A4, landscape
    from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
    from reportlab.lib.units import mm
    from reportlab.platypus import (
        Image,
        KeepTogether,
        Paragraph,
        SimpleDocTemplate,
        Spacer,
        Table,
        TableStyle,
    )

    profile = profile_csv(csv_content)
    buffer = BytesIO()

    document = SimpleDocTemplate(
        buffer,
        pagesize=landscape(A4),
        rightMargin=14 * mm,
        leftMargin=14 * mm,
        topMargin=14 * mm,
        bottomMargin=14 * mm,
        title="DataLens AI - EDA Report",
        author="DataLens AI",
    )

    styles = getSampleStyleSheet()
    styles.add(ParagraphStyle(
        name="ReportTitle",
        parent=styles["Title"],
        alignment=TA_CENTER,
        textColor=colors.HexColor("#174ea6"),
        spaceAfter=8,
    ))
    styles.add(ParagraphStyle(
        name="SmallCell",
        parent=styles["BodyText"],
        fontSize=8,
        leading=10,
        wordWrap="CJK",
    ))

    story = [
        Paragraph("DataLens AI - Exploratory Data Analysis", styles["ReportTitle"]),
        Paragraph("Automatically generated report from your CSV dataset.", styles["Normal"]),
        Spacer(1, 6 * mm),
    ]

    summary_data = [
        ["Rows", "Columns", "Missing values", "Duplicate rows"],
        [
            str(profile["rows"]),
            str(profile["columns_count"]),
            str(profile["missing_values_total"]),
            str(profile["duplicate_rows"]),
        ],
    ]
    summary_table = Table(summary_data, colWidths=[55 * mm] * 4)
    summary_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#174ea6")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("BACKGROUND", (0, 1), (-1, 1), colors.HexColor("#eef4ff")),
        ("ALIGN", (0, 0), (-1, -1), "CENTER"),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#d8dee9")),
        ("TOPPADDING", (0, 0), (-1, -1), 8),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
    ]))
    story.extend([
        summary_table,
        Spacer(1, 7 * mm),
        Paragraph("Column Overview", styles["Heading2"]),
    ])

    column_data = [[
        "Column", "Data type", "Missing", "Missing %", "Unique values"
    ]]
    for column in profile["columns"]:
        column_data.append([
            Paragraph(str(column["name"]).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;"), styles["SmallCell"]),
            str(column["dtype"]),
            str(column["missing_values"]),
            f'{column["missing_percentage"]:.2f}%',
            str(column["unique_values"]),
        ])

    available_width = landscape(A4)[0] - 28 * mm
    column_widths = [
        available_width * 0.34,
        available_width * 0.20,
        available_width * 0.13,
        available_width * 0.16,
        available_width * 0.17,
    ]
    column_table = Table(
        column_data,
        colWidths=column_widths,
        repeatRows=1,
    )
    column_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#174ea6")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#d8dee9")),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [
            colors.white, colors.HexColor("#f5f7fb")
        ]),
        ("TOPPADDING", (0, 0), (-1, -1), 5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
    ]))
    story.extend([column_table, Spacer(1, 7 * mm)])

    story.append(Paragraph("Numeric Summary", styles["Heading2"]))
    numeric_summary = profile["numeric_summary"]
    if numeric_summary:
        summary_rows = [["Statistic"] + [str(name) for name in numeric_summary]]
        stat_names = list(next(iter(numeric_summary.values())).keys())
        for stat in stat_names:
            summary_rows.append([
                str(stat),
                *[
                    str(numeric_summary[column].get(stat, "N/A"))
                    for column in numeric_summary
                ],
            ])
        summary_width = available_width / max(len(summary_rows[0]), 1)
        numeric_table = Table(
            summary_rows,
            colWidths=[summary_width] * len(summary_rows[0]),
            repeatRows=1,
        )
        numeric_table.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#174ea6")),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#d8dee9")),
            ("FONTSIZE", (0, 0), (-1, -1), 7),
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ]))
        story.extend([numeric_table, Spacer(1, 7 * mm)])
    else:
        story.append(Paragraph("No numeric columns were available.", styles["Normal"]))

    numeric_columns = [
        column["name"]
        for column in profile["columns"]
        if column["dtype"] in {"int64", "int32", "float64", "float32"}
    ]

    story.append(Paragraph("Visualizations", styles["Heading2"]))
    charts_added = 0

    for column in numeric_columns[:3]:
        try:
            image_bytes = create_histogram(csv_content, column)
            image = Image(BytesIO(image_bytes), width=110 * mm, height=70 * mm)
            story.append(KeepTogether([
                Paragraph(
                    "Distribution: " + str(column).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;"),
                    styles["Heading3"],
                ),
                image,
            ]))
            story.append(Spacer(1, 4 * mm))
            charts_added += 1
        except ValueError:
            continue

    if len(numeric_columns) >= 2:
        try:
            image_bytes = create_correlation_heatmap(csv_content)
            story.append(KeepTogether([
                Paragraph("Correlation Heatmap", styles["Heading3"]),
                Image(BytesIO(image_bytes), width=110 * mm, height=80 * mm),
            ]))
            charts_added += 1
        except ValueError:
            pass

    if charts_added == 0:
        story.append(Paragraph("No suitable numeric charts were available.", styles["Normal"]))

    document.build(story)
    return buffer.getvalue()
